"""Live regression checks for generated-column and sequence-default inspection."""

import pytest
from alembic import command
from alembic.util import AutogenerateDiffsDetected, CommandError
from sqlalchemy import text

from app.db.manage import alembic_config

pytestmark = pytest.mark.integration


def check_connection(connection):
    config = alembic_config()
    config.attributes["connection"] = connection
    command.check(config)


def test_drift_check_preserves_reservation_sequence(connection):
    query = text("SELECT last_value, is_called FROM reservation_number_seq")
    before = connection.execute(query).one()
    check_connection(connection)
    assert connection.execute(query).one() == before


@pytest.mark.parametrize(
    "ddl",
    [
        "ALTER TABLE reservations ALTER COLUMN reservation_number "
        "SET DEFAULT ('CHANGED-' || nextval('reservation_number_seq')::text)",
        "ALTER TABLE books ALTER COLUMN language SET DEFAULT 'en'",
        "ALTER TABLE books ALTER COLUMN title DROP NOT NULL",
    ],
)
def test_drift_check_still_detects_real_changes(connection, ddl):
    connection.execute(text(ddl))
    with pytest.raises(AutogenerateDiffsDetected):
        check_connection(connection)


def test_drift_check_rejects_changed_generated_expression(connection):
    connection.execute(text("ALTER TABLE notifications DROP COLUMN related_entity_id"))
    connection.execute(
        text(
            "ALTER TABLE notifications ADD COLUMN related_entity_id uuid "
            "GENERATED ALWAYS AS ('00000000-0000-0000-0000-000000000001'::uuid) STORED NOT NULL"
        )
    )
    with pytest.raises(CommandError, match="Generated expression drift"):
        check_connection(connection)
